<?php

namespace Cube\Data\DataToObject\Generator;

use Cube\Data\AutoDataToObject;
use Cube\Data\Bunch;
use Cube\Data\Classes\ArrayOf;
use Cube\Data\DataToObject;
use Cube\Data\DataToObject\Generator\Descriptors\DtoClass;
use Cube\Data\DataToObject\Generator\Descriptors\DtoDirection;
use Cube\Data\DataToObject\Generator\Descriptors\DtoProperty;
use Cube\Data\DataToObject\Generator\Descriptors\Types\ClassType;
use Cube\Data\DataToObject\Generator\Descriptors\Types\ListType;
use Cube\Data\DataToObject\Generator\Descriptors\Types\MapType;
use Cube\Utils\Text;

/**
 * Writes the classes described by a source, one file per class : an `Output` class is a `DataToObject`
 * built from received data, an `Input` class an `AutoDataToObject` you build and send
 */
class DtoWriter
{
    /**
     * @param bool $lenient every property becomes optional and nullable, whatever the source declares
     */
    public function __construct(
        protected GenerationTarget $target,
        protected string $generator,
        protected bool $lenient = false,
    ) {}

    /**
     * @param DtoClass[] $classes
     *
     * @return string[] written files
     */
    public function write(array $classes): array
    {
        $files = [];
        foreach ($classes as $class)
            $files[] = $this->target->write($class->namespace, $class->name, $this->render($class));

        return $files;
    }

    public function render(DtoClass $class): string
    {
        $isInput = DtoDirection::Input === $class->direction;
        $references = $this->referencesOf($class);
        $types = new TypeRenderer($this->target, $references, objectsAtAnyDepth: $isInput);

        $parent = $class->parent
            ? $types->nameOf($class->parent)
            : $references->nameOf($isInput ? AutoDataToObject::class : DataToObject::class);

        $body = match (true) {
            null !== $class->parent => '',
            $isInput => "\n".$this->inputBodyOf($class, $types),
            default => "\n".$this->outputBodyOf($class, $types),
        };

        // Fragments are interpolated after toFile(), which would otherwise strip their own indentation
        return Text::interpolate(Text::toFile('
            <?php

            namespace {namespace};

            {uses}/**
             * Generated by {generator}, regenerate it rather than editing it
             */
            class {name} extends {parent}
            {{body}
            }
            ', 3), [
            'namespace' => $this->target->fullNamespaceOf($class->namespace),
            'uses' => $references->toUses(),
            'generator' => $this->generator,
            'name' => $class->name,
            'parent' => $parent,
            'body' => $body,
        ])."\n";
    }

    protected function outputBodyOf(DtoClass $class, TypeRenderer $types): string
    {
        $names = $this->propertyNamesOf($class);

        // A required parameter after an optional one is deprecated, so the optional ones go last
        list($required, $optional) = Bunch::wrap($class->properties)->partitionFilter(fn (DtoProperty $property) => $this->isOptional($property));
        $parameters = [...$required, ...$optional];

        return $this->blocks(
            $this->keysOf($class, $names),
            $this->constructorOf($class, $parameters, $names, $types),
        );
    }

    protected function inputBodyOf(DtoClass $class, TypeRenderer $types): string
    {
        $names = $this->propertyNamesOf($class);

        // An optional property stays uninitialized until it is set, so toArray() leaves it out instead of sending null
        list($required, $optional) = Bunch::wrap($class->properties)->partitionFilter(fn (DtoProperty $property) => $this->isOptional($property));

        $declarations = Bunch::wrap($optional)
            ->map(fn (DtoProperty $property) => ($types->needsDocType($property->type) ? '    /** @var '.$this->docTypeOf($class, $property, $types)." */\n" : '')
                .'    public '.$this->nativeTypeOf($class, $property, $types).' $'.$names[$property->key].';')
            ->toArray();

        $objectProperties = Bunch::wrap($class->properties)
            ->filter(fn (DtoProperty $property) => $property->type instanceof MapType)
            ->map(fn (DtoProperty $property) => '            '.var_export($names[$property->key], true).',');

        $objectKeys = $objectProperties->count() ? Text::interpolate(Text::toFile('
                protected function objectKeys(): array
                {
                    return [
            {properties}
                    ];
                }
            ', 3), ['properties' => $objectProperties->join("\n")]) : '';

        return $this->blocks(...[
            ...$declarations,
            $this->keysOf($class, $names),
            $objectKeys,
            count($required) ? $this->constructorOf($class, $required, $names, $types) : '',
        ]);
    }

    protected function blocks(string ...$blocks): string
    {
        return implode("\n\n", array_filter($blocks));
    }

    /**
     * @param array<string,string> $names
     */
    protected function keysOf(DtoClass $class, array $names): string
    {
        $entries = Bunch::wrap($class->properties)
            ->filter(fn (DtoProperty $property) => $names[$property->key] !== $property->key)
            ->map(fn (DtoProperty $property) => '            '.var_export($names[$property->key], true).' => '.var_export($property->key, true).',');

        if (!$entries->count())
            return '';

        return Text::interpolate(Text::toFile('
                public static function keys(): array
                {
                    return [
            {entries}
                    ];
                }
            ', 3), ['entries' => $entries->join("\n")]);
    }

    /**
     * @param DtoProperty[]        $parameters
     * @param array<string,string> $names
     */
    protected function constructorOf(DtoClass $class, array $parameters, array $names, TypeRenderer $types): string
    {
        if (!count($parameters))
            return '    public function __construct() {}';

        $tags = Bunch::wrap($parameters)
            ->filter(fn (DtoProperty $property) => $types->needsDocType($property->type))
            ->map(fn (DtoProperty $property) => '     * @param '.$this->docTypeOf($class, $property, $types).' $'.$names[$property->key]);

        $doc = $tags->count() ? Text::interpolate(Text::toFile('
                /**
            {tags}
                 */
            ', 3), ['tags' => $tags->join("\n")])."\n" : '';

        return $doc.Text::interpolate(Text::toFile('
                public function __construct(
            {parameters}
                ) {}
            ', 3), [
            'parameters' => Bunch::wrap($parameters)
                ->map(fn (DtoProperty $property) => $this->parameterOf($class, $property, $names[$property->key], $types))
                ->join("\n"),
        ]);
    }

    protected function parameterOf(DtoClass $class, DtoProperty $property, string $name, TypeRenderer $types): string
    {
        $type = $property->type;

        $attribute = DtoDirection::Output === $class->direction && $type instanceof ListType && $type->item instanceof ClassType
            ? '        #['.$types->referenceOf(ArrayOf::class).'('.$types->nameOf($type->item)."::class)]\n"
            : '';

        $default = DtoDirection::Output === $class->direction && $this->isOptional($property) ? ' = null' : '';

        return "{$attribute}        public {$this->nativeTypeOf($class, $property, $types)} \${$name}{$default},";
    }

    protected function nativeTypeOf(DtoClass $class, DtoProperty $property, TypeRenderer $types): string
    {
        $nativeType = $types->nativeTypeOf($property->type);

        return 'mixed' !== $nativeType && $this->isNullable($class, $property) ? '?'.$nativeType : $nativeType;
    }

    protected function docTypeOf(DtoClass $class, DtoProperty $property, TypeRenderer $types): string
    {
        return $types->docTypeOf($property->type).($this->isNullable($class, $property) ? '|null' : '');
    }

    /**
     * Two keys can give the same PHP name (`first_name` and `firstName`) : the later ones get a number
     *
     * @return array<string,string> key => PHP name
     */
    protected function propertyNamesOf(DtoClass $class): array
    {
        $names = [];
        foreach ($class->properties as $property)
            $names[$property->key] = DtoNames::unique(
                DtoNames::propertyName($property->key),
                $names
            );

        return $names;
    }

    protected function isOptional(DtoProperty $property): bool
    {
        return $this->lenient || !$property->required;
    }

    /**
     * An optional `Output` property defaults to null, an optional `Input` property is left uninitialized instead
     */
    protected function isNullable(DtoClass $class, DtoProperty $property): bool
    {
        return $this->lenient
            || $property->nullable
            || (DtoDirection::Output === $class->direction && !$property->required);
    }

    protected function referencesOf(DtoClass $class): PhpReferences
    {
        $isInput = DtoDirection::Input === $class->direction;

        $classes = Bunch::wrap($class->properties)
            ->flatMap(fn (DtoProperty $property) => TypeRenderer::classesOf($property->type, deep: $isInput))
            ->map(fn (ClassType $type) => $this->target->fullNameOf($type))
            ->toArray();

        $hasArrayOf = !$isInput && Bunch::wrap($class->properties)->any(fn (DtoProperty $property) => $property->type instanceof ListType && $property->type->item instanceof ClassType);

        return new PhpReferences($this->target->fullNamespaceOf($class->namespace), $class->name, [
            $class->parent ? $this->target->fullNameOf($class->parent) : ($isInput ? AutoDataToObject::class : DataToObject::class),
            ...($hasArrayOf ? [ArrayOf::class] : []),
            ...$classes,
        ]);
    }
}
